import express from "express";
import cors from "cors";
import cookieParser from "cookie-parser";
import helmet from "helmet";
import authRoutes from "./routes/auth.js";
const app=express();
app.disable("x-powered-by");app.use(helmet());app.use(cors({origin:process.env.CLIENT_ORIGIN||"http://localhost:5173",credentials:true}));app.use(express.json({limit:"10kb"}));app.use(cookieParser());
app.get("/api/health",(_req,res)=>res.json({status:"ok"}));app.use("/api/auth",authRoutes);
app.use((_req,res)=>res.status(404).json({message:"Endpoint not found."}));
app.use((error,_req,res,_next)=>{console.error(error);res.status(500).json({message:process.env.NODE_ENV==="production"?"Something went wrong.":error.message||"Internal server error."});});
export default app;
